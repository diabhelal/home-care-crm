#!/usr/bin/env python3
"""Migration ledger: every SQL file in supabase/migrations (registered = applied to the live project, per
supabase/proposed/APPLIED.md) and supabase/proposed (source / not yet applied), with a hash of the NORMALISED SQL
(comments and whitespace removed) so a proposed file and its registered copy can be matched even though their header
comments differ. Reads files only; never connects to any database.

  python3 scripts/migration_ledger.py           # rewrite docs/MIGRATION_LEDGER.md
  python3 scripts/migration_ledger.py --check   # CI: fail if the ledger is stale or a registered copy drifted
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = ROOT / "supabase" / "migrations"
PROP = ROOT / "supabase" / "proposed"
OUT = ROOT / "docs" / "MIGRATION_LEDGER.md"


def normalised_hash(path: pathlib.Path) -> str:
    lines = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = re.sub(r"--.*$", "", line)          # SQL line comments (no '--' inside string literals in these files)
        line = re.sub(r"\s+", " ", line).strip()
        if line:
            lines.append(line)
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()[:12]


def raw_hash(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def build():
    migs = sorted(MIG.glob("*.sql"))
    props = sorted(PROP.glob("*.sql"))
    by_norm = {normalised_hash(m): m.name for m in migs}
    problems = []
    rows_m = [f"| `{m.name}` | `{raw_hash(m)}` | `{normalised_hash(m)}` |" for m in migs]
    rows_p = []
    for p in props:
        match = by_norm.get(normalised_hash(p))
        status = f"registered as `{match}`" if match else "**not applied** to the live project (proposed only)"
        rows_p.append(f"| `{p.name}` | `{normalised_hash(p)}` | {status} |")
    # a proposed file whose number shares its name with a registered migration must match it exactly (no SQL drift)
    for p in props:
        suffix = p.stem.split("_", 1)[1]
        twins = [m for m in migs if m.stem.split("_", 1)[1] == suffix]
        if twins and normalised_hash(twins[0]) != normalised_hash(p):
            problems.append(f"{p.name} differs in SQL from its registered copy {twins[0].name}")
    text = "\n".join([
        "# Migration ledger",
        "",
        "Generated by `scripts/migration_ledger.py` (do not edit by hand; CI runs it with `--check`). It reads the repository",
        "only. \"Registered\" means the file is in `supabase/migrations/`, which by the project rule happens only after it",
        "was applied to the live project (see `supabase/proposed/APPLIED.md`). It is **not** a query of the live database:",
        "comparing against the live `supabase_migrations.schema_migrations` table is a separate, owner-approved read.",
        "`sql hash` ignores comments and whitespace, so a proposed file and its registered copy match when the SQL is identical.",
        "",
        f"## Registered migrations ({len(migs)})",
        "",
        "| file | file hash | sql hash |",
        "|---|---|---|",
        *rows_m,
        "",
        f"## Proposed SQL ({len(props)})",
        "",
        "| file | sql hash | status |",
        "|---|---|---|",
        *rows_p,
        "",
    ])
    return text, problems


def main():
    text, problems = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            problems.append("docs/MIGRATION_LEDGER.md is stale: run python3 scripts/migration_ledger.py")
        for p in problems:
            print("LEDGER:", p)
        print(f"migration ledger: {len(problems)} problem(s)")
        sys.exit(1 if problems else 0)
    OUT.write_text(text, encoding="utf-8")
    for p in problems:
        print("LEDGER:", p)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
